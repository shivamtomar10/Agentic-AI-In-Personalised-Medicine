"""Agent input/output contracts. AGENTS.md Rule 3."""
from __future__ import annotations

from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, model_validator

from src.contracts.delta import DeltaReport
from src.contracts.evidence import ClinicalClaim, EvidenceRef
from src.contracts.patient import PatientState
from src.contracts.recommendation import ClinicalAction, DraftPrescription, RiskFlag, ValidationReport


class ExecutionMode(str, Enum):
    FULL_RERUN = "full_rerun"
    SELECTIVE_REPLAN = "selective_replan"


class DifferentialItem(BaseModel):
    condition: str
    rank: int = Field(..., ge=1)
    supporting: List[str] = Field(default_factory=list)
    refuting: List[str] = Field(default_factory=list)
    note: str = ""


class AgentOutput(BaseModel):
    """Standardized output of all agents."""
    agent_name: str
    claims: List[ClinicalClaim] = Field(default_factory=list)
    actions: List[ClinicalAction] = Field(default_factory=list)
    risk_flags: List[RiskFlag] = Field(default_factory=list)
    draft_prescriptions: List[DraftPrescription] = Field(default_factory=list, description="Draft prescriptions generated by TreatmentAgent for clinician verification")
    evidence_pool: List[EvidenceRef] = Field(default_factory=list)
    differential: List[DifferentialItem] = Field(default_factory=list)
    data_quality_flags: List[str] = Field(default_factory=list)
    narrative: Optional[str] = None
    validation_report: Optional[ValidationReport] = None
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    abstained: bool = False
    abstention_reason: Optional[str] = None
    execution_metadata: Dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @model_validator(mode="after")
    def validate_abstention(self) -> "AgentOutput":
        if self.abstained and not self.abstention_reason:
            raise ValueError("An abstaining agent must provide an explicit abstention_reason.")
        return self


class AgentInput(BaseModel):
    """Standardized input for all agents."""
    agent_name: str
    patient_state: PatientState
    previous_state: Optional[PatientState] = None
    history: List[PatientState] = Field(default_factory=list)
    delta_report: Optional[DeltaReport] = None
    query: Optional[str] = None
    upstream_outputs: Dict[str, AgentOutput] = Field(default_factory=dict, description="Outputs of agents that ran before this one")
    context: Dict[str, Any] = Field(default_factory=dict)
    execution_mode: ExecutionMode = ExecutionMode.SELECTIVE_REPLAN
